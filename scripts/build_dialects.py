def research_reading(pinyin):
    # Cantonese rows give "mandarin|jyutping". Typing happens in the first.
    plain = (pinyin or "").split("|")[0].lower().replace("ü", "v")
    plain = "".join(c for c in unicodedata.normalize("NFD", plain) if not unicodedata.combining(c))
    plain = re.sub(r"[\s'\-0-9]", "", plain)
    return plain if re.fullmatch(r"[a-z]+", plain) else None


def rejection(row):
    if row["regionalSignal"] == "none":
        return "no regional difference"
    if (row["mandarinPerMillion"] or 0) >= MANDARIN_CEILING:
        return "universal in Mandarin"
    if any(word in (row["quoteCheck"] or "") for word in ("unreadable", "miss")):
        return "source not verified"
    if EXCLUDED_SOURCE.search(row["sourceUrl"] + row["sourceTitle"]):
        return "licence"
    if not row["safeDefault"] or UNSUITABLE.search(row["risk"] or ""):
        return "unsuitable"
    if len(row["form"]) > LONGEST_FORM or not all("\u4e00" <= c <= "\u9fff" for c in row["form"]):
        return "not typeable"
    return None if research_reading(row["pinyin"]) else "no reading"


def researched():
    """Per region, the endings and intensifying words that pass."""
    endings, words, rejected = {}, {}, Counter()
    for row in json.loads(RESEARCH.read_text(encoding="utf-8")):
        reason = rejection(row)
        if reason:
            rejected[reason] += 1
            continue
        table = words if row["kind"] == "intensifier" else endings
        key = (row["form"], research_reading(row["pinyin"]))
        region = table.setdefault(row["region"], {})
        region[key] = max(region.get(key, 0), row["tier"])
    return endings, words, rejected


def merged_entries(region, words):
    entries = [{"text": text, "readings": readings.split("|"), "boost": boost, "kind": kind,
                **({"note": note} if note else {})}
               for text, readings, boost, kind, note in region["entries"]]
    known = {entry["text"]: entry for entry in entries}
    for (text, reading), tier in sorted(words.get(region["id"], {}).items()):
        if text in known:
            if reading not in known[text]["readings"]:
                known[text]["readings"].append(reading)
        else:
            known[text] = {"text": text, "readings": [reading], "boost": tier, "kind": "程度"}
            entries.append(known[text])
    return entries


def build() -> dict:
    endings, words, rejected = researched()
    seen_ids = set()
    for region in REGIONS:
        if region["id"] in seen_ids:
            raise SystemExit("duplicate region id: " + region["id"])
        seen_ids.add(region["id"])
        seen_text = set()
        for text, readings, boost, kind, note in region["entries"]:
            if not text or len(text) > 64:
                raise SystemExit("bad text in " + region["id"])
            if text in seen_text:
                raise SystemExit("duplicate text in %s: %s" % (region["id"], text))
            seen_text.add(text)
            if not (1 <= boost <= 5):
                raise SystemExit("bad boost in %s: %s" % (region["id"], text))
            if not kind:
                raise SystemExit("missing kind in %s: %s" % (region["id"], text))
            if note and len(note) > 80:
                raise SystemExit("note too long in %s: %s" % (region["id"], text))
            parts = readings.split("|")
            if not parts:
                raise SystemExit("missing reading in %s: %s" % (region["id"], text))
            for reading in parts:
                if not re.fullmatch(r"[a-z]+", reading):
                    raise SystemExit("bad reading %r in %s: %s" % (reading, region["id"], text))
    return {
        "format_version": 1,
        "revision": "2026-11-05",
        "notice": "方言常用语汇编；不是完整方言词典，按普通话拼音或常见本地罗马字近似录入。逐条来源见 DataSources/dialect-sources.json。",
        "sources": [
            "《中国语言地图集》方言分区与通用介绍",
            "各地方言概述与常用语公开资料（经人工筛选、改写和整理）",
            "普通话拼音与粤语、闽南语常见罗马字习惯",
            "Wiktionary、CC-Canto、Wikipedia 与已发表的方言研究",
        ],
        "regions": [
            {
                "id": region["id"],
                "name": region["name"],
                "family": region["family"],
                "provinces": region["provinces"],
                "summary": region["summary"],
                "entries": merged_entries(region, words),
                "endings": [{"text": text, "reading": reading, "tier": tier}
                            for (text, reading), tier in sorted(endings.get(region["id"], {}).items())],
            }
            for region in REGIONS
        ],
    }


def main() -> int:
    data = build()
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("dialect catalogue is out of date:", OUTPUT, file=sys.stderr)
            return 1
        print("dialect catalogue is current:", len(data["regions"]), "regions,",
              sum(len(r["entries"]) for r in data["regions"]), "entries")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print("wrote", OUTPUT, len(data["regions"]), "regions,",
          sum(len(r["entries"]) for r in data["regions"]), "entries,",
          sum(len(r["endings"]) for r in data["regions"]), "endings")
    print("largest region:", max(len(r["entries"]) for r in data["regions"]), "entries;",
          "regions without endings:", sum(not r["endings"] for r in data["regions"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
